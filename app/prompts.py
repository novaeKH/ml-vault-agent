def build_context(chunks: Iterable[dict[str, str]], max_chars: int) -> str:
    parts: list[str] = []
    used = 0
    for index, chunk in enumerate(chunks, start=1):
        header = (
            f"[Фрагмент {index}: {chunk['title']} > {chunk['heading']} | "
            f"type={chunk['note_type']} | area={chunk['area']}]\n"
        )
        piece = header + chunk["text"].strip()
        if parts and used + len(piece) > max_chars:
            break
        if not parts and len(piece) > max_chars:
            piece = piece[:max_chars]
        parts.append(piece)
        used += len(piece)
    return "\n\n---\n\n".join(parts) if parts else "(Релевантные фрагменты не найдены.)"


def system_prompt(mode: str, context: str) -> str:
    mode_prompt = MODE_PROMPTS.get(mode, MODE_PROMPTS["chat"])
    return f"{COMMON}\n\n{mode_prompt}\n\nКОНТЕКСТ ИЗ VAULT:\n\n{context}"
